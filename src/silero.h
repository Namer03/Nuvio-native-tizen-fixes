// Silero VAD (16 kHz, v5/v6 architecture) in plain C, for the audio subtitle
// sync. Port of the official model (https://github.com/snakers4/silero-vad,
// MIT) following the approach of NuvioTV Reshaped's SileroVad.kt:
//
//   64 samples of context + 512 new samples, reflect-padded by 64 on the right
//   -> STFT (256 points, hop 128, periodic Hann, 4 frames, 129-bin magnitude)
//   -> 4 x conv1d k=3 pad=1 + ReLU (129->128 s1, 128->64 s2, 64->64 s2, 64->128 s1)
//   -> LSTM cell 128 -> ReLU -> linear 128->1 -> sigmoid = speech probability.
//
// One call per 32 ms of audio, ~0.4 M multiply-adds, no allocation per call.
// The weights (src/silero_pesos.c, generated by tools/silero/converter.py, float16
// in the binary, float32 in memory once: ~1 MB) are only linked where audio sync
// runs: Android and the .tpk 6+. Elsewhere silero_disponivel() is 0 and audvad.c
// keeps its energy VAD.
#ifndef NV_SILERO_H
#define NV_SILERO_H

#define SILERO_BLOCO 512   // samples per call (32 ms at 16 kHz)
#define SILERO_CTX   64

typedef struct {
  float ctx[SILERO_CTX];
  float h[128], c[128];
} SileroEstado;

// 1 when the weights are linked into this build and loaded (the first call
// converts them; thread-safe).
int silero_disponivel(void);
void silero_zerar(SileroEstado *s);
// x: SILERO_BLOCO samples in [-1, 1]. Returns the speech probability (0..1),
// or -1 when the model is not available.
float silero_prob(SileroEstado *s, const float *x);

// src/silero_pesos.c
extern const unsigned silero_pesos_n;
extern const unsigned short silero_pesos_f16[];

#endif
