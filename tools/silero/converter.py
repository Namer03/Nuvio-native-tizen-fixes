#!/usr/bin/env python3
"""Generates src/silero_pesos.c from the official Silero VAD 16 kHz weights.

  pip install silero-vad torch numpy
  python3 tools/silero/converter.py            # writes src/silero_pesos.c

Source: the `silero-vad` Python package (data/silero_vad.jit, the same 16 kHz
weights as data/silero_vad.onnx; the bundled .safetensors holds a different
set and does not reproduce the ONNX output),
Copyright (c) 2020-present Silero Team, MIT License
(https://github.com/snakers4/silero-vad). The STFT layer is a periodic
Hann-windowed DFT, so it is computed in C (src/silero.c) and not shipped.
Everything else is stored as IEEE float16 (~487 KB), in this order:
conv1..conv4 weight/bias, lstm weight_ih, weight_hh, bias_ih, bias_hh,
final_conv weight, bias.
"""
import hashlib, os, sys
import numpy as np
import torch
import silero_vad

NOMES = {"conv%d.%s" % (i + 1, t): "encoder.%d.reparam_conv.%s" % (i, t) for i in range(4) for t in ("weight", "bias")}
NOMES.update({"lstm_cell." + t: "decoder.rnn." + t for t in ("weight_ih", "weight_hh", "bias_ih", "bias_hh")})
NOMES.update({"final_conv.weight": "decoder.decoder.2.weight", "final_conv.bias": "decoder.decoder.2.bias",
              "stft_conv.weight": "stft.forward_basis_buffer"})

ORDEM = [("conv1.weight", 128 * 129 * 3), ("conv1.bias", 128), ("conv2.weight", 64 * 128 * 3), ("conv2.bias", 64),
         ("conv3.weight", 64 * 64 * 3), ("conv3.bias", 64), ("conv4.weight", 128 * 64 * 3), ("conv4.bias", 128),
         ("lstm_cell.weight_ih", 512 * 128), ("lstm_cell.weight_hh", 512 * 128),
         ("lstm_cell.bias_ih", 512), ("lstm_cell.bias_hh", 512), ("final_conv.weight", 128), ("final_conv.bias", 1)]

def main():
    raiz = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    fonte = os.path.join(os.path.dirname(silero_vad.__file__), "data", "silero_vad.jit")
    sd = {k: v.numpy() for k, v in torch.jit.load(fonte, map_location="cpu")._model.state_dict().items()}
    w = {nosso: sd[deles] for nosso, deles in NOMES.items()}
    sha = hashlib.sha256(open(fonte, "rb").read()).hexdigest()
    # The STFT basis must be the periodic Hann DFT that src/silero.c computes.
    n = np.arange(256); k = np.arange(129)[:, None]; han = 0.5 - 0.5 * np.cos(2 * np.pi * n / 256)
    B = w["stft_conv.weight"][:, 0, :]
    assert np.abs(B[:129] - np.cos(2 * np.pi * k * n / 256) * han).max() < 1e-5
    assert np.abs(B[129:] + np.sin(2 * np.pi * k * n / 256) * han).max() < 1e-5
    tudo = []
    for nome, tam in ORDEM:
        v = w[nome].astype(np.float32).ravel()
        assert v.size == tam, (nome, v.size, tam)
        tudo.append(v)
    h = np.concatenate(tudo).astype(np.float16).view(np.uint16)
    versao = getattr(silero_vad, "__version__", "") or os.popen("pip show silero-vad 2>/dev/null | sed -n 's/^Version: //p'").read().strip()
    saida = os.path.join(raiz, "src", "silero_pesos.c")
    with open(saida, "w") as f:
        f.write("// GENERATED by tools/silero/converter.py: do not edit.\n")
        f.write("// Silero VAD 16 kHz weights (silero-vad %s, data/silero_vad.jit = silero_vad.onnx,\n" % versao)
        f.write("// sha256 %s).\n" % sha)
        f.write("// Copyright (c) 2020-present Silero Team. MIT License:\n")
        f.write("// https://github.com/snakers4/silero-vad/blob/master/LICENSE\n")
        f.write("// float16, without the STFT layer (computed in src/silero.c).\n")
        f.write("// Only linked where audio sync runs: Android and the .tpk 6+ (and tests that ask).\n")
        f.write('#include "silero.h"\n')
        f.write("#if defined(NV_ANDROID) || (defined(NV_TPK) && !defined(NV_TPK40)) || defined(NV_SILERO_PESOS)\n")
        f.write("const unsigned silero_pesos_n = %du;\n" % h.size)
        f.write("const unsigned short silero_pesos_f16[%d] = {\n" % h.size)
        for i in range(0, h.size, 16):
            f.write("  " + ",".join("0x%04x" % x for x in h[i:i + 16]) + ",\n")
        f.write("};\n#else\nconst unsigned silero_pesos_n = 0u;\nconst unsigned short silero_pesos_f16[1] = { 0 };\n#endif\n")
    print("wrote", saida, h.size, "values", h.size * 2, "bytes")

if __name__ == "__main__":
    sys.exit(main())
